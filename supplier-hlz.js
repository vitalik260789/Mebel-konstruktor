// Цвет для 3D по коду/названию декора
function decorColor(name, code) {
  const n = name.toLowerCase();
  const table = [
    [/альпин|белый|фарфор|алебастр|хромикс|флитвуд|аланд белая|полярн/, '#f1efea'], [/чёрн|черн|лес/, '#2a2a2b'], [/антрацит|графит|уголь|тёмно-серый|темно-серый/, '#4a4c50'],
    [/кашемир|бежев|крем|коттон|карамель|миндаль|песок|камель/, '#d8cbb6'], [/серый|серая|оникс|лава|галька|гавана|бетон|сланец|ангора|шёлк|шелк/, '#a8aaac'],
    [/зелён|зелен|шалфей|фьёрд|эвкалипт зел/, '#7d9a7a'], [/голуб|синий|индиго|озеро|деним/, '#5b7fa3'], [/красн|бургунд|розов|сиена|карри|жёлт|желт/, '#b9614a'],
    [/венге|термо|эвкалипт|трюфель|тёмн|темн|коричнев|табак|коньяк|шерман|чарльстон|орех/, '#6e4e36'],
    [/дуб|ясень|бук|клён|клен|берёз|берез|сосна|пихта|акация|вишня|гикори|каштан|кокоболо|древесина|ноче/, '#c49a6c'],
    [/металл|бронз|кобра|серебр|мрамор/, '#9a9488'],
  ];
  for (const [re, c] of table) if (re.test(n)) return c;
  return code && code[0] === 'H' ? '#c49a6c' : '#d9d4cc';
}

